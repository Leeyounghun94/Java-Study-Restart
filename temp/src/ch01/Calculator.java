package ch01;

public class Calculator {

//    main()안에는 다양한 실행문이 실행이 된다.
//    println(""); 에서 "" 안에 글자 내용을 출력하는 실행문이고
//    실행문은 변수 선언, 변수값 저장, 메서드 호출에 해당하는 코드를 말하는 것이다.

//    알고있지만, 실행문이 끝나면 세미콜론(;)을 붙여야 한다는 점 잊지 말자.

    public static void main(String[] args) {

        int x = 1;
        int y = 2;
        int result = x + y;
        System.out.println(result);
        // x와 y를 변수 선언하고 값을 저장한다. 그리고 변수 result를 선언하고 x, y를 더한다.
        // 더한 값을 result로 출력해보자.

        //  3
    }
}
